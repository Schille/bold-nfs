    #[test]
    fn serialize_a_thing() {
        use bytes::BytesMut;
        let mut buf = BytesMut::with_capacity(1024);
        
        let ser = PUTFH4res::serializer(nfsstat4::serializer(nfsstat4::NFS4ERR_ACCESS));
        ser(&mut buf);
        assert_eq!(*buf, *b"\x00\x00\x00\x0D");
    }

    #[test]
    fn serialize_b_thing() {
        use bytes::BytesMut;
        let mut buf = BytesMut::with_capacity(1024);
        
        let nfs = GETFH4resok { object: nfs_fh4(Bytes::from("125763")) };
        let ser = GETFH4res::serializer(GETFH4res::NFS4_OK(nfs));
        ser(&mut buf);
        assert_eq!(*buf, *b"\x00\x00\x00\x00");
    }

